#!/usr/bin/env python3
"""Turn a folder of Phosphor SVGs into icons.js (path data only). Symbols use the fill weight;
the chrome glyphs check, x, caret-left, caret-right, plus and magnifying-glass use the bold weight, as SF Symbols does.

Usage: python3 -I tools/build_icons.py tools/phosphor icons.js

Each file must be a single <path> in a 256 x 256 viewBox. Path data is checked
against the SVG path grammar's characters before it goes into the module.
"""
import json
import os
import re
import sys

SAFE = re.compile(r"^[MmLlHhVvCcSsQqTtAaZz0-9.,\s-]+$")


def main(src, out):
    icons = {}
    for name in sorted(os.listdir(src)):
        if not name.endswith(".svg"):
            continue
        text = open(os.path.join(src, name), encoding="utf-8").read()
        m = re.fullmatch(r'\s*<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="currentColor"><path d="([^"]+)"/></svg>\s*', text)
        if not m or not SAFE.match(m.group(1)):
            sys.exit(f"unexpected content in {name}")
        icons[name[:-4]] = m.group(1)
    body = ",\n".join(f"  {json.dumps(k)}: {json.dumps(v)}" for k, v in icons.items())
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Icons from Phosphor Icons 2.1.1, fill weight (check, x, caret-left, caret-right, plus and magnifying-glass in bold) (MIT licence, see icons/PHOSPHOR-LICENSE.txt).\n")
        f.write("// Generated by tools/build_icons.py; edit the source SVGs, not this file.\n")
        f.write(f"export const ICONS = {{\n{body},\n}};\n\n")
        f.write("export function icon(name, cls = '') {\n")
        f.write("  return `<svg class=\"i ${cls}\" viewBox=\"0 0 256 256\" aria-hidden=\"true\" focusable=\"false\"><path d=\"${ICONS[name]}\"/></svg>`;\n")
        f.write("}\n")
    print(f"wrote {len(icons)} icons to {out}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
